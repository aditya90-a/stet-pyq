_TABLE = {ord(k): v for k, (v, _) in GLYPHS.items()}
# a dependent sign split off its consonant by a stray space ("ष्ट्र ीय") is re-attached; the short-i
# (U+093F) is excluded because in visual order it legitimately follows a space ("तथा िवलंिबत")
_SPACE_BEFORE_SIGN = re.compile(r"[  ]+(?=[ाी-्ँ-ःॢॣ])")
# a half consonant split from the next consonant ("व्यवस् था")
_SPACE_AFTER_HALANT = re.compile(r"(?<=्)[  ]+(?=[क-हक़-य़])")
_UNMAPPED = re.compile(r"[Ā-ͯ]")


def is_encoded(s: str) -> bool:
    return any(ord(c) in _TABLE for c in s)


def decode(s: str) -> tuple[str, list[str]]:
    """Decode one Nirmala-UI string from the 2021 sheets into logical-order Unicode Hindi."""
    if not s:
        return s, []
    fixes = []
    out = s.translate(_TABLE)
    if out != s:
        fixes.append("glyph-map-decoded")
    out = _SPACE_BEFORE_SIGN.sub("", out)
    out, fx = hindi.repair(out, visual_order=True)
    fixes += fx
    # only after the reph has been moved: a composite glyph such as "ीर्" ends in a halant but is followed
    # by a real word space
    out = _SPACE_AFTER_HALANT.sub("", out)
    if _UNMAPPED.search(out):
        fixes.append("unmapped-glyph-left")
    return out, fixes
